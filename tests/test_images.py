def test_offline_lists_the_missing_images_and_pulls_nothing(ctx: Context, host: FakeHost) -> None:
    sources(host)
    ctx.options.offline = True
    alpine = ctx.versions.verify_alpine
    host.responses[("podman", "image", "exists", alpine)] = MISSING
    with pytest.raises(
        images.ImagesError, match=rf"TK_OFFLINE=1: 1 images are missing .*\n  {re.escape(alpine)}"
    ):
        images.ensure(ctx, K8S)
    assert store_pulls(host) == []


def test_a_pull_that_fails_once_is_retried_twice_fails(ctx: Context, host: FakeHost) -> None:
    sources(host)
    img = ctx.versions.verify_alpine
    host.responses[("podman", "image", "exists", img)] = MISSING
    host.responses[("podman", "pull", "-q", img)] = [
        Result(125, "", "tls: internal error"),
        Result(0, "", ""),
    ]
    images.ensure(ctx, K8S)
    assert store_pulls(host).count(img) == 2 and any("retrying" in line for line in host.lines)
    host.calls.clear()
    host.responses[("podman", "pull", "-q", img)] = Result(125, "", "tls: internal error")
    with pytest.raises(
        images.ImagesError, match=rf"pull of {re.escape(img)} failed twice; rerun to resume"
    ):
        images.ensure(ctx, K8S)


def test_node_image_pull_build_refresh_offline(ctx: Context, host: FakeHost) -> None:
    host.responses[("podman", "image", "exists", NODE)] = MISSING
    images.ensure_node_image(ctx, K8S)
    assert ["podman", "pull", NODE] in [c.argv for c in host.calls]
    host.calls.clear()
    host.responses[("podman", "pull", NODE)] = Result(125, "", "manifest unknown")
    images.ensure_node_image(ctx, K8S)
    build = next(c.argv for c in host.calls if c.argv[:2] == ["podman", "build"])
    assert build == [
        "podman",
        "build",
        "--build-arg",
        f"VER={K8S}",
        "--build-arg",
        "CRIO=v1.37.2",
        "--force-rm",
        "-t",
        NODE,
        str(ctx.paths.home / "images" / "node"),
    ]
    host.responses[("podman", "image", "exists")] = MISSING
    host.responses[("podman", "pull")] = Result(125, "", "manifest unknown")
    with pytest.raises(images.ImagesError, match=r"no crio entry for Kubernetes minor 1\.35"):
        images.ensure_node_image(ctx, "1.35.5")
    del host.responses[("podman", "image", "exists")]
    del host.responses[("podman", "pull")]
    host.calls.clear()
    del host.responses[("podman", "image", "exists", NODE)]
    ctx.options.refresh = True
    host.responses[("podman", "image", "inspect")] = [
        Result(0, "sha256:old\n", ""),
        Result(0, "sha256:new\n", ""),
    ]
    host.responses[("podman", "pull", NODE)] = Result(0, "", "")
    images.ensure_node_image(ctx, K8S)
    assert f"  {NODE} refreshed (the tag was republished)" in host.lines
    ctx.options.refresh = False
    ctx.options.offline = True
    host.responses[("podman", "image", "exists", NODE)] = MISSING
    with pytest.raises(images.ImagesError, match="TK_OFFLINE=1 forbids pulling or building"):
        images.ensure_node_image(ctx, K8S)


def test_prune_refuses_while_a_cluster_uses_the_version(ctx: Context, host: FakeHost) -> None:
    ctx.options.assume_yes = True
    (ctx.paths.clusters_dir / "demo").mkdir(parents=True)
    (ctx.paths.clusters_dir / "demo" / "cluster.yaml").write_text(
        model.dumps(ctx.require_cluster())
    )
    (ctx.paths.images_dir / K8S).mkdir(parents=True)
    with pytest.raises(
        images.ImagesError, match=f"image store {K8S} is used by cluster\\(s\\): demo"
    ):
        images.prune(ctx, K8S)
    (ctx.paths.clusters_dir / "demo" / "cluster.yaml").unlink()
    images.prune(ctx, K8S)
    assert ["rm", "-rf", str(ctx.paths.images_dir / K8S)] in [c.argv for c in host.calls]
    with pytest.raises(images.ImagesError, match=r"no image store for Kubernetes 1\.30\.0"):
        images.prune(ctx, "1.30.0")


def test_lock_serialises_two_ensures(tmp_path: Path) -> None:
    order: list[str] = []
    lock = tmp_path / "x.lock"

    def worker(name: str) -> None:
        with images.with_lock(lock):
            order.append(f"{name}-in")
            threading.Event().wait(0.05)
            order.append(f"{name}-out")

    a = threading.Thread(target=worker, args=("a",))
    b = threading.Thread(target=worker, args=("b",))
    a.start()
    b.start()
    a.join()
    b.join()
    assert order in (["a-in", "a-out", "b-in", "b-out"], ["b-in", "b-out", "a-in", "a-out"])
    assert lock.exists()


def test_phase_done_and_run(ctx: Context, host: FakeHost) -> None:
    sources(host)
    host.dirs.add(images.store_dir(ctx.paths, K8S))
    host.files[images.conf_path(ctx.paths, K8S)] = images.storage_conf(ctx.paths, K8S)
    assert images_phase.done(ctx)
    # missing for done(), the Runner's done() and the pull's own check; present once pulled
    host.responses[("podman", "image", "exists", NODE)] = [MISSING, MISSING, MISSING, PRESENT]
    assert not images_phase.done(ctx)
    Runner([images_phase.PHASE]).run(ctx)
    assert f"  {NODE} pulled" in host.lines and images_phase.done(ctx)


def test_store_conf_is_written_inside_the_lock(
    ctx: Context, host: FakeHost, monkeypatch: pytest.MonkeyPatch
) -> None:
    sources(host)
    order: list[str] = []
    real = images.with_lock

    def spy(path: Path) -> AbstractContextManager[None]:
        order.append("lock")
        return real(path)

    monkeypatch.setattr(images, "with_lock", spy)
    images.ensure(ctx, K8S)
    calls = [c.argv[:2] for c in host.calls]
    data_at = calls.index(["mkdir", str(ctx.paths.data_dir)])
    conf_at = calls.index(["mkdir", str(ctx.paths.images_dir / K8S)])
    assert order == ["lock"] and data_at < conf_at


