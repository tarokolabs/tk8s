K8S = "1.37.1"
NODE = f"ghcr.io/tarokolabs/tk8s/node:v{K8S}"
KUBEADM_LIST = (
    f"registry.k8s.io/kube-apiserver:v{K8S}\nregistry.k8s.io/kube-controller-manager:v{K8S}\n"
    f"registry.k8s.io/kube-scheduler:v{K8S}\nregistry.k8s.io/kube-proxy:v{K8S}\n"
    "registry.k8s.io/coredns/coredns:v1.14.6\nregistry.k8s.io/pause:3.10.2\n"
    "registry.k8s.io/etcd:3.7.0-0\n"
)
CILIUM_DRY = (
    '      image: "quay.io/cilium/cilium:v1.20.2@sha256:aaaa"\n'
    '      image: "quay.io/cilium/operator-generic:v1.20.2@sha256:bbbb"\n'
    '      image: "quay.io/cilium/cilium-envoy:v1.37.6-1@sha256:cccc"\n'
)
MISSING = Result(1, "", "")
PRESENT = Result(0, "", "")


def sources(host: FakeHost) -> None:
    host.responses[("podman", "run", "--rm", "--entrypoint", "kubeadm", NODE)] = Result(
        0, KUBEADM_LIST, ""
    )
    host.responses[("cilium", "install")] = Result(0, CILIUM_DRY, "")
    host.responses[("id", "-u")] = Result(0, "1000\n", "")
    host.responses[("id", "-g")] = Result(0, "1000\n", "")


def store_pulls(host: FakeHost) -> list[str]:
    return [
        c.argv[-1]
        for c in host.calls
        if c.argv[:3] == ["podman", "pull", "-q"] and "CONTAINERS_STORAGE_CONF" in c.env
    ]


def test_wanted_is_derived_sorted_and_unique(ctx: Context, host: FakeHost) -> None:
    sources(host)
    w = images.wanted(ctx, K8S)
    assert w == sorted(set(w)) and len(w) == 15
    assert f"registry.k8s.io/kube-apiserver:v{K8S}" in w
    assert "quay.io/cilium/cilium:v1.20.2@sha256:aaaa" in w
    assert "registry.k8s.io/metrics-server/metrics-server:v0.9.0" in w
    assert "docker.io/rancher/local-path-provisioner:v0.0.37" in w
    assert "haproxy" not in " ".join(w) and ctx.versions.verify_alpine in w
    kube = next(c for c in host.calls if c.argv[:2] == ["podman", "run"])
    assert kube.argv[-3:] == ["list", "--kubernetes-version", f"v{K8S}"] and kube.sudo
    cil = next(c for c in host.calls if c.argv[0] == "cilium")
    assert "--chart-directory" in cil.argv
    assert cil.env == {"KUBECONFIG": "/nonexistent", "HOME": "/tmp"}


