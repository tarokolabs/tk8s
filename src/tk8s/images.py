"""The shared read-only image store: one containers/storage graphroot per Kubernetes version under
IMAGES_DIR/<version>, root-owned (rootful podman writes it); nodes mount it read-only as an
additional image store, so a create pulls nothing. Only tkctl writes here."""

import fcntl
import re
import time
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from pathlib import Path

from . import model, podman
from .create import router
from .datatree import data_dirs
from .host import HostError
from .model import node_image
from .paths import Paths
from .phases import Context, confirm


class ImagesError(Exception):
    pass


def store_dir(paths: Paths, k8s: str) -> Path:
    return paths.images_dir / k8s


def conf_path(paths: Paths, k8s: str) -> Path:
    return paths.images_dir / f"{k8s}.conf"


def storage_conf(paths: Paths, k8s: str) -> str:
    return (
        f"# Generated by tkctl: the shared image store for Kubernetes {k8s}. Used only through\n"
        "# CONTAINERS_STORAGE_CONF by images:ensure; nodes mount the graphroot read-only.\n"
        "[storage]\n"
        'driver = "overlay"\n'
        f'graphroot = "{store_dir(paths, k8s)}"\n'
        f'runroot = "/run/taroko-images/{k8s}"\n'
        "\n"
        "[storage.options.overlay]\n"
        'mountopt = "nodev,metacopy=on"\n'
    )


def _store_env(paths: Paths, k8s: str) -> dict[str, str]:
    return {"CONTAINERS_STORAGE_CONF": str(conf_path(paths, k8s))}


@contextmanager
def with_lock(path: Path) -> Iterator[None]:
    """One writer per version directory. The file stays so a waiting process keeps its inode."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(f, fcntl.LOCK_UN)


def init_store(ctx: Context, k8s: str) -> None:
    """The root-owned graphroot and the version's storage.conf; runs under the version's lock."""
    ctx.host.mkdir(store_dir(ctx.paths, k8s), sudo=True)
    conf = conf_path(ctx.paths, k8s)
    if ctx.host.read(conf) != storage_conf(ctx.paths, k8s):
        ctx.host.write(conf, storage_conf(ctx.paths, k8s))


# ---- the node image on the host


def node_image_present(ctx: Context, k8s: str) -> bool:
    return podman.exists(ctx, "image", node_image(k8s))


def cilium_cli_present(ctx: Context) -> bool:
    return (
        ctx.host.run(["cilium", "version", "--client"], capture=True, check=False).returncode == 0
    )


def _digest(ctx: Context, image: str) -> str:
    r = ctx.host.run(
        ["podman", "image", "inspect", "--format", "{{.Digest}}", image],
        sudo=True,
        capture=True,
        check=False,
    )
    return r.stdout.strip() if r.returncode == 0 else ""


def _ensure_image(
    ctx: Context,
    image: str,
    *,
    kind: str,
    build_dir: str,
    build_args: Callable[[], list[str]],
    building: str,
    report_digest: bool,
) -> None:
    """Pull the tag, or build it locally from images/<build_dir> when it is not published.
    With refresh, pull again even when the tag is present: a republished tag replaces the
    stale local image."""
    present = podman.exists(ctx, "image", image)
    if present and not ctx.options.refresh:
        return
    if ctx.options.offline:
        raise ImagesError(
            f"{kind} {image} is not present and TK_OFFLINE=1 forbids pulling or building it"
        )
    before = _digest(ctx, image) if present and report_digest else ""
    if ctx.host.run(["podman", "pull", image], sudo=True, check=False).returncode == 0:
        if not present:
            ctx.say(f"  {image} pulled")
        elif not report_digest:
            ctx.say(f"  {image} refreshed")
        elif before == _digest(ctx, image):
            ctx.say(f"  {image} is up to date")
        else:
            ctx.say(f"  {image} refreshed (the tag was republished)")
        return
    args = build_args()
    ctx.say(f"  {image} is not published; building locally ({building})")
    ctx.host.run(
        [
            "podman",
            "build",
            *args,
            "--force-rm",
            "-t",
            image,
            str(ctx.paths.home / "images" / build_dir),
        ],
        sudo=True,
    )


def ensure_node_image(ctx: Context, k8s: str) -> None:
    """The node image: pulled by tag, or built locally when the tag is not published (needs a
    crio entry for the minor)."""

    def args() -> list[str]:
        crio = ctx.versions.crio_for(k8s)
        if crio is None:
            raise ImagesError(
                f"versions.yaml has no crio entry for Kubernetes minor {k8s.rsplit('.', 1)[0]}; "
                f"cannot build {node_image(k8s)}"
            )
        return ["--build-arg", f"VER={k8s}", "--build-arg", f"CRIO={crio}"]

    _ensure_image(
        ctx,
        node_image(k8s),
        kind="node image",
        build_dir="node",
        build_args=args,
        building="the first build takes a few minutes",
        report_digest=True,
    )


def ensure_router_image(ctx: Context) -> None:
    """The router image, pulled by tag or built from images/router/ when the tag is not published
    (a release that has not pushed yet, or a build number bumped locally)."""
    v = ctx.versions
    _ensure_image(
        ctx,
        router.image(v),
        kind="router image",
        build_dir="router",
        build_args=lambda: [
            "--build-arg",
            f"VYOS={v.vyos}",
            "--build-arg",
            f"SHA256={v.vyos_sha256}",
        ],
        building="downloads the VyOS ISO, a few minutes",
        report_digest=False,
    )


# ---- what a version needs


def ensure_cilium_cli(ctx: Context) -> None:
    if cilium_cli_present(ctx):
        return
    if ctx.options.offline:
        raise ImagesError("cilium CLI is not installed and TK_OFFLINE=1 forbids downloading it")
    v = ctx.versions.cilium_cli
    url = f"https://github.com/cilium/cilium-cli/releases/download/{v}/cilium-linux-amd64.tar.gz"
    tgz = ctx.host.run_bytes(["curl", "-fsSL", "--retry", "3", "--retry-all-errors", url])
    ctx.host.run_bytes(["tar", "-xz", "-C", "/usr/local/bin", "cilium"], sudo=True, input=tgz)
    ctx.say(f"  cilium CLI {v} installed to /usr/local/bin")


_IMAGE_LINE = re.compile(r'^ *(?:- )?image: *"?([^"\s]+)"?', re.M)


def wanted(ctx: Context, k8s: str) -> list[str]:
    """Every image a cluster of this version needs, sorted and unique. Nothing is hand-written:
    control-plane tags from kubeadm inside the node image, cilium's from `cilium install
    --dry-run`, the rest from the checked-in manifests and versions.yaml."""
    v, home = ctx.versions, ctx.paths.home
    kube = ctx.host.run(
        [
            "podman",
            "run",
            "--rm",
            "--entrypoint",
            "kubeadm",
            node_image(k8s),
            "config",
            "images",
            "list",
            "--kubernetes-version",
            f"v{k8s}",
        ],
        sudo=True,
        capture=True,
        check=False,
    )
    if kube.returncode != 0 or not kube.stdout.strip():
        raise ImagesError(f"kubeadm in {node_image(k8s)} listed no images: {kube.stderr.strip()}")
    chart = home / "manifests" / f"cilium-{v.cilium}"
    cil = ctx.host.run(
        ["cilium", "install", "--version", v.cilium, "--chart-directory", str(chart), "--dry-run"],
        env={"KUBECONFIG": "/nonexistent", "HOME": "/tmp"},
        capture=True,
        check=False,
    )
    cilium_images = _IMAGE_LINE.findall(cil.stdout)
    if cil.returncode != 0 or not cilium_images:
        raise ImagesError(f"cilium install --dry-run listed no images: {cil.stderr.strip()}")
    manifests = [
        home / "manifests" / f"metrics-server.{v.metrics_server.lstrip('v')}.yaml",
        home / "manifests" / f"local-path-storage.{v.local_path_provisioner.lstrip('v')}.yaml",
    ]
    from_files = [img for m in manifests for img in _IMAGE_LINE.findall(m.read_text())]
    pins = [v.verify_busybox, v.verify_alpine, v.verify_agnhost]
    return sorted(set(kube.stdout.split()) | set(cilium_images) | set(from_files) | set(pins))


def listing(ctx: Context, k8s: str) -> list[tuple[str, str]]:
    """What `get images` prints: the node and router images in the host's podman storage first,
    then the store's status(). Only looks: status() needs the node image and the cilium CLI to
    compute the list, and this names tkctl pull images when either is missing."""
    if not node_image_present(ctx, k8s):
        raise ImagesError(
            f"node image {node_image(k8s)} is not on this host; run tkctl pull images --k8s {k8s}"
        )
    if not cilium_cli_present(ctx):
        raise ImagesError(f"cilium CLI is not installed; run tkctl pull images --k8s {k8s}")
    rows = status(ctx, k8s)
    out: list[tuple[str, str]] = []
    for img in (node_image(k8s), router.image(ctx.versions)):
        out.append(("present" if podman.exists(ctx, "image", img) else "missing", img))
    return out + rows


def status(ctx: Context, k8s: str) -> list[tuple[str, str]]:
    """("present" | "missing", image) for every wanted image of the store, in list order. Only
    looks; the caller makes sure the node image and the cilium CLI, which wanted() runs, are on
    the host."""
    env = _store_env(ctx.paths, k8s)
    have_store = ctx.host.exists(conf_path(ctx.paths, k8s)) and ctx.host.exists(
        store_dir(ctx.paths, k8s)
    )
    out: list[tuple[str, str]] = []
    for img in wanted(ctx, k8s):
        present = (
            have_store
            and ctx.host.run(
                ["podman", "image", "exists", img], sudo=True, env=env, check=False
            ).returncode
            == 0
        )
        out.append(("present" if present else "missing", img))
    return out


# ---- filling, pruning, copying


def _pull(ctx: Context, k8s: str, img: str) -> None:
    """One retry: registry CDNs hiccup (TLS resets, HTTP/2 errors); a second failure stops."""
    env = _store_env(ctx.paths, k8s)
    if ctx.host.run(["podman", "pull", "-q", img], sudo=True, env=env, check=False).returncode == 0:
        return
    ctx.say(f"  pull of {img} failed; retrying in 5s")
    time.sleep(ctx.options.retry_delay)
    try:
        ctx.host.run(["podman", "pull", "-q", img], sudo=True, env=env)
    except HostError as err:
        raise ImagesError(f"images: pull of {img} failed twice; rerun to resume") from err


def ensure(ctx: Context, k8s: str) -> None:
    """Every image the version needs is in the store (skips what is there; TK_OFFLINE=1 checks
    only). Serialised per version: a second ensure waits for the first, then finds everything."""
    data_dirs(ctx)  # tkctl pull images may be the first command on a fresh host
    with with_lock(ctx.paths.images_dir / f"{k8s}.lock"):
        init_store(ctx, k8s)
        start = time.monotonic()
        ensure_node_image(ctx, k8s)
        ensure_router_image(ctx)
        ensure_cilium_cli(ctx)
        rows = status(ctx, k8s)
        present = [i for s, i in rows if s == "present"]
        missing = [i for s, i in rows if s == "missing"]
        where = store_dir(ctx.paths, k8s)
        if not missing:
            ctx.say(f"  images {k8s}: {len(present)} present, nothing to pull ({where})")
            return
        if ctx.options.offline:
            listed = "\n".join(f"  {i}" for i in missing)
            raise ImagesError(
                f"TK_OFFLINE=1: {len(missing)} images are missing from {where}; "
                f"run tkctl pull images --k8s {k8s} online:\n{listed}"
            )
        for img in missing:
            _pull(ctx, k8s, img)
            ctx.say(f"  pulled {img}")
        secs = int(time.monotonic() - start)
        ctx.say(
            f"  images {k8s}: {len(present)} present, {len(missing)} pulled in {secs}s ({where})"
        )


def clusters_using(paths: Paths, k8s: str) -> list[str]:
    return sorted(
        p.parent.name for p in paths.clusters_dir.glob("*/cluster.yaml") if model.peek(p)[1] == k8s
    )


def prune(ctx: Context, k8s: str) -> None:
    """Delete a version's store; refused while a cluster of that version exists."""
    where, conf = store_dir(ctx.paths, k8s), conf_path(ctx.paths, k8s)
    if not (where.exists() or conf.exists()):
        raise ImagesError(
            f"no image store for Kubernetes {k8s} under {ctx.paths.images_dir} (tkctl get images)"
        )
    confirm(
        ctx,
        f"Delete the shared image store for Kubernetes {k8s} under {ctx.paths.images_dir}? [y/N] ",
        ImagesError,
    )
    with with_lock(ctx.paths.images_dir / f"{k8s}.lock"):
        using = clusters_using(ctx.paths, k8s)
        if using:
            raise ImagesError(
                f"image store {k8s} is used by cluster(s): {' '.join(using)}; delete them first"
            )
        ctx.host.run(["rm", "-rf", str(where)], sudo=True)
        conf.unlink(missing_ok=True)
    ctx.say(f"  image store {k8s} deleted")
